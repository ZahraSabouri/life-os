import assert from 'node:assert/strict';
import {readFile,mkdtemp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {Store,localDay,validatePatch} from '../lib/store.mjs';
import {selectJobs} from '../lib/matching.mjs';

const base=JSON.parse(await readFile(new URL('../data/jobs.json',import.meta.url),'utf8'));
const directory=await mkdtemp(fileURLToPath(new URL('../data/test-dates-',import.meta.url)));
const store=await new Store(base,directory).init();
assert(store.jobs().every(j=>j.addedOn==='2026-09-13'));
assert(store.jobs().every(j=>j.advertisedOn===''));
assert.equal(localDay(new Date('2026-09-16T23:32:36.557Z')),'2026-09-17');
const vacancy={role:'Date verification role',company:'Test company',url:'https://example.org/date-test',description:'Paid part-time employment, 16 hours per week.',source:'Employer careers',checked:'2026-09-01',advertisedOn:'2026-08-24',deadline:'2026-11-01'};
const dry=await store.ingest({runId:'date-check',jobs:[vacancy]},0,true);
assert.equal(dry.added.length,1);assert.equal(store.state.customJobs.length,0);
const first=await store.ingest({runId:'date-check',jobs:[vacancy]},0);
const id=first.added[0];const addedOn=store.jobs().find(j=>j.id===id).addedOn;
assert.equal(addedOn,localDay());assert.notEqual(addedOn,vacancy.checked);
await store.patch(id,{advertisedOn:'2026-08-23',deadline:'2026-11-02',notes:'Keep this',status:'Applied',priority:'P1'},1);
await store.ingest({runId:'date-refresh',jobs:[{...vacancy,checked:'2026-10-06',advertisedOn:'2026-08-25',deadline:'2026-10-31'}]},2);
const updated=store.jobs().find(j=>j.id===id);
assert.equal(updated.addedOn,addedOn);assert.equal(updated.advertisedOn,'2026-08-23');assert.equal(updated.deadline,'2026-11-02');assert.equal(updated.notes,'Keep this');assert.equal(updated.status,'Applied');
assert.equal(store.state.observations[id].advertisedOn,'2026-08-25');
await assert.rejects(store.patch(id,{addedOn:'2026-01-01'},3),/Unsupported field/);
await assert.rejects(store.ingest({runId:'cannot-reset-date',jobs:[{...vacancy,addedOn:'2026-01-01'}]},3),/Invalid evidence field/);
await assert.rejects(store.ingest({runId:'invalid-advert-date',jobs:[{...vacancy,advertisedOn:'2026-02-30'}]},3),/valid date/);
assert.throws(()=>validatePatch({advertisedOn:'yesterday'}),/valid date/);
const reopened=await new Store(base,directory).init();
assert.equal(reopened.jobs().find(j=>j.id===id).addedOn,addedOn);
const backup=structuredClone(reopened.export());
const invalid=structuredClone(backup);invalid.progress.customJobs[0].addedOn='2026-02-30';
await assert.rejects(reopened.restore(invalid,3),/Invalid date added/);
await reopened.restore(backup,3);assert.equal(reopened.jobs().find(j=>j.id===id).advertisedOn,'2026-08-23');
const manual=await reopened.add({role:'Manual date check',company:'Test',advertisedOn:'2026-10-05'},4);
assert.equal(manual.job.addedOn,localDay());assert.equal(manual.job.advertisedOn,'2026-10-05');
const rows=[{...updated,id:'unknown',addedOn:'',advertisedOn:''},{...updated,id:'older',addedOn:'2026-09-13',advertisedOn:'2026-08-01'},{...updated,id:'newer',addedOn:'2026-10-06',advertisedOn:'2026-10-01'}];
for(const sort of ['added','advertised'])assert.deepEqual(selectJobs(rows,{scope:'all',sort}).map(r=>r.job.id),['newer','older','unknown']);
const legacy=structuredClone(backup.progress);
legacy.observations={};legacy.overrides={};
legacy.customJobs=['CUSTOM-f2dbe053-b374-4f29-8455-254b7a3940ec','CUSTOM-e71d6ad7-bc73-413d-b8f2-17c8797fc2df','CUSTOM-unknown-legacy'].map(id=>{const j={...legacy.customJobs[0],id};delete j.addedOn;return j;});
const recovered=store.validateState(legacy);
assert.equal(recovered.customJobs.find(j=>j.id==='CUSTOM-f2dbe053-b374-4f29-8455-254b7a3940ec').addedOn,'2026-09-17');
assert.equal(recovered.customJobs.find(j=>j.id==='CUSTOM-e71d6ad7-bc73-413d-b8f2-17c8797fc2df').addedOn,'2026-10-06');
assert.equal(recovered.customJobs.find(j=>j.id==='CUSTOM-unknown-legacy').addedOn,undefined);
assert.deepEqual(recovered.overrides,legacy.overrides);
console.log('PASS: truthful date recovery, first-import dates, publication-date validation, immutable added date, personal edits, restart/restore, manual dates and unknown-last sorting.');
